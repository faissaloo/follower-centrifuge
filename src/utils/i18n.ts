export const translations = {
  en,
  es,
} as const;

export function getInitialLanguage(): Language {
  try {
    const saved = localStorage.getItem(LANGUAGE_STORAGE_KEY);
    if (saved === 'en' || saved === 'es') {
      return saved;
    }
    if (typeof navigator !== 'undefined' && navigator.language && navigator.language.toLowerCase().startsWith('es')) {
      return 'es';
    }
  } catch {
    // localStorage/navigator can be unavailable (privacy mode); fall through.
  }
  return 'en';
}

export function saveLanguage(lang: Language): void {
  try {
    localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
  } catch {
    // Ignore storage failures; the in-memory language still works for this session.
  }
}

/**
 * Translate `key` into `lang`, replacing `%s` placeholders with `args` in order.
 * Unknown keys fall back to English and finally to the key itself.
 */
export function t(lang: Language, key: TranslationKey, ...args: Array<string | number>): string {
  // Every key exists in both dictionaries (enforced by the Spanish dictionary's
  // `Record<TranslationKey, string>` type), so this lookup cannot miss.
  const dict: Record<TranslationKey, string> = lang === 'es' ? translations.es : translations.en;
  let text: string = dict[key];
  for (const arg of args) {
    text = text.replace('%s', String(arg));
  }
  return text;
}
